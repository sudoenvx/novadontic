function createListCase(
  id: string,
  patientName: string,
  doctorName: string,
  clinicName: string,
  caseType: string,
  dueDate: string,
  priority: 'Normal' | 'Rush',
  stage: CasePipelineCase['stage'],
): CasePipelineCase {
  return {
    id,
    patientName,
    patientCode: 'Pending',
    clinicName,
    doctorName,
    request: caseType,
    caseType,
    categoryId: priority === 'Rush' ? 'remake' : 'new',
    categoryName: priority === 'Rush' ? 'Remake' : 'New case',
    arch: 'Not provided',
    units: 0,
    status: dueDate.startsWith('Overdue') ? 'Needs attention' : dueDate === 'Due tomorrow' ? 'On track' : 'Due today',
    priority,
    stage,
    dueDate,
    createdAt: '18 Sep',
    productionSteps: [],
    activities: [],
  }
}
